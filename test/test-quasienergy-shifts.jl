@testitem "Quasienergy shifts of a rotating two-state coupling" tags=[:unit, :fast] begin
    using LinearAlgebra
    using Levels.PeriodicDynamics
    using Unitful

    # One rotating Fourier component gives an isolated two-state Floquet
    # block, whose exact eigenvalues also fix the sideband sign convention.
    Δ = angular(5.0u"MHz")
    ω = angular(2.0u"MHz")
    g = angular(0.01u"MHz")
    H0 = Diagonal([zero(Δ), Δ])
    H1 = [0.0 im; 0.0 0.0] .* g
    detuning = Δ - ω
    pt = -g^2 / detuning
    exact = (detuning - sqrt(detuning^2 + 4g^2)) / 2

    @test quasienergy_shift(H0, H1, ω, 1) ≈ pt
    @test quasienergy_shift(H0, H1, ω, 2) ≈ -pt
    @test quasienergy_shift(H0, H1, ω, 1, Floquet(; harmonic_cutoff=2)) ≈ exact
    @test quasienergy_shift(H0, H1, ω, 2, Floquet(; harmonic_cutoff=2)) ≈ -exact
    terms = quasienergy_shift_contributions(H0, H1, ω, 1)
    @test length(terms) == 1
    @test only(terms).k == 2
    @test only(terms).sideband == 1
    @test only(terms).coupling ≈ g
    @test only(terms).detuning ≈ -detuning
    @test only(terms).shift ≈ pt
    @test unit(only(terms).shift) == u"rad/µs"
end

@testitem "Generic within-manifold quasienergy shifts" tags=[:unit, :fast] begin
    using LinearAlgebra
    using Levels.PeriodicDynamics
    using Unitful

    s = Eigenstructure(sr88, "S_1/2", "D_3/2"; B=0.5u"mT")
    basis = Levels.basis(s)
    lower = StateSpec("D_3/2", -3//2)
    upper = StateSpec("D_3/2", 3//2)
    i, k = stateindex(basis, lower), stateindex(basis, upper)
    ω = angular(50.0u"MHz")
    X = zeros(ComplexF64, length(basis), length(basis)) .* u"rad/µs"
    # A Δm = 3 drive cannot be generated by a magnetic dipole interaction.
    X[i, k] = X[k, i] = angular(10.0u"kHz")
    drives = [HarmonicDrive(X, 0.3)]
    Δ = state_offset(s, lower) - state_offset(s, upper)
    expected = abs2(X[i, k] / 2) * (1 / (Δ - ω) + 1 / (Δ + ω))

    @test quasienergy_shift(s, lower, ω, drives) ≈ expected
    @test quasienergy_shift(s, i, ω, drives) ≈ expected
    @test quasienergy_shift(s, lower, ω, drives, Floquet()) ≈ expected rtol = 1e-5
    pair = quasienergy_shift(s, lower => upper, ω, drives)
    @test pair.lower ≈ expected
    @test pair.upper ≈ -expected
    @test pair.shift ≈ -2expected
    terms = quasienergy_shift_contributions(s, lower, ω, drives)
    @test length(terms) == 2
    @test all(t -> t.state == upper, terms)
    @test sum(t.shift for t in terms) ≈ expected

    # The structure wrapper must refuse couplings it would discard when
    # extracting a fine-structure manifold, in either matrix orientation.
    for (row, col) in ((1, i), (i, 1))
        cross = copy(X)
        cross[row, col] = angular(1.0u"kHz")
        invalid = [HarmonicDrive(cross, 0.0)]
        for method in (PerturbationTheory(), Floquet())
            @test_throws ArgumentError quasienergy_shift(s, lower, ω, invalid, method)
            @test_throws ArgumentError quasienergy_shift(
                s,
                basis[1] => lower,
                ω,
                invalid,
                method,
            )
        end
        @test_throws ArgumentError quasienergy_shift_contributions(s, lower, ω, invalid)
    end
    @test_throws ArgumentError quasienergy_shift(s, lower, ω, HarmonicDrive[])
    @test_throws ArgumentError quasienergy_shift(
        s,
        lower,
        ω,
        [HarmonicDrive(X[1:2, 1:2], 0.0)],
    )
end

@testitem "Magnetic-phasor quasienergy convenience API" tags=[:unit, :fast] begin
    using Levels.PeriodicDynamics
    using Unitful

    s = Eigenstructure(sr88, "S_1/2", "D_5/2"; B=0.5u"mT")
    probe = StateSpec("S_1/2", -1//2) => StateSpec("D_5/2", 1//2)
    ω = angular(50u"MHz")
    for b in ([1.0, 0.0, 0.0]u"µT", [1.0, -1.0im, 0.5]u"µT")
        drives = zeeman_drives(s, b)
        for method in (PerturbationTheory(), Floquet(; harmonic_cutoff=3))
            pair = quasienergy_shift(s, probe, ω, drives, method)
            @test ac_zeeman_shift(s, probe, ω, b, method) == pair
            @test ac_zeeman_shift(s, probe.first, ω, b, method) == pair.lower
            @test ac_zeeman_shift(
                s,
                stateindex(Levels.basis(s), probe.first),
                ω,
                b,
                method,
            ) == pair.lower
            @test unit(pair.shift) == u"rad/µs"
        end
        @test !applicable(quasienergy_shift, s, probe, ω, b)
        @test !applicable(ac_zeeman_shift, s, probe, ω, drives)
    end
    @test PerturbationTheory() isa QuasienergyShiftMethod
    @test Floquet() isa QuasienergyShiftMethod
end
